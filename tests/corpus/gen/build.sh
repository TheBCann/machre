#!/bin/bash
# build.sh -- (re)generate the machre test corpus. Idempotent: every fixture is rebuilt
# from the sources in gen/src; the only persistent random input is gen/src/random.bin,
# which is created once and then reused so the high-entropy fixture stays stable.
#
# Requires: Xcode command line tools (Apple clang/ld64, lipo, codesign, plutil, xattr),
#           python3, and the Zig nightly at $ZIG (override with ZIG=... env var).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CORPUS="$(cd "$HERE/.." && pwd)"
SRC="$HERE/src"
CC="${CC:-/usr/bin/clang}"                       # Apple clang (NOT Homebrew llvm)
ZIG="${ZIG:-zig}"                                 # nightly zig on PATH, or set ZIG
CODESIGN=/usr/bin/codesign
LIPO=/usr/bin/lipo
PLUTIL=/usr/bin/plutil
XATTR=/usr/bin/xattr
# -g0: no DWARF (symbols still come from the nlist). -Wl,-reproducible: this ld (ld-1267) otherwise
# emits a *random* LC_UUID on every link, which changes the UUID and every linker-signed cdhash.
CFLAGS=(-O0 -g0 -fno-omit-frame-pointer -Wl,-reproducible)
BUILD="$(mktemp -d -t machre-corpus-build)"        # scratch for intermediates (generated .c, zig cache)
trap 'rm -rf "$BUILD"' EXIT

mkdir -p "$CORPUS/malformed" "$CORPUS/truth"
cd "$CORPUS"

log() { printf '[build] %s\n' "$*"; }

# ---------------------------------------------------------------- a. hello-c / x86_64 / fat
log "hello-c (arm64 thin)"
"$CC" -arch arm64 "${CFLAGS[@]}" -o hello-c "$SRC/hello.c"
log "hello-x86_64"
"$CC" -arch x86_64 "${CFLAGS[@]}" -o hello-x86_64 "$SRC/hello.c"
log "hello-fat (lipo)"
"$LIPO" -create -output hello-fat hello-c hello-x86_64

# ---------------------------------------------------------------- b. hello-objc
log "hello-objc"
"$CC" -arch arm64 "${CFLAGS[@]}" -fobjc-arc -framework Foundation -o hello-objc "$SRC/hello_objc.m"

# ---------------------------------------------------------------- c. dylib + consumer
log "libhello.dylib"
"$CC" -arch arm64 "${CFLAGS[@]}" -dynamiclib \
    -install_name @rpath/libhello.dylib \
    -compatibility_version 1.0 -current_version 1.2.3 \
    -Wl,-rpath,@loader_path/../Frameworks \
    -o libhello.dylib "$SRC/libhello.c"
log "hello-usedylib"
"$CC" -arch arm64 "${CFLAGS[@]}" -L. -lhello \
    -Wl,-rpath,@executable_path -Wl,-rpath,@executable_path/../Frameworks \
    -o hello-usedylib "$SRC/use_dylib.c"

# ---------------------------------------------------------------- d. signing variants
log "hello-adhoc (codesign -s -)"
cp -f hello-c hello-adhoc
"$CODESIGN" -s - -f -i com.machre.corpus.hello-adhoc hello-adhoc
log "hello-entitled (codesign -s - --entitlements)"
cp -f hello-c hello-entitled
"$CODESIGN" -s - -f -i com.machre.corpus.hello-entitled --entitlements "$SRC/entitlements.plist" hello-entitled
log "hello-unsigned (codesign --remove-signature)"
cp -f hello-c hello-unsigned
"$CODESIGN" --remove-signature hello-unsigned

# ---------------------------------------------------------------- e. entropy / packer-name heuristics
log "high-entropy (64 KiB urandom in __RANDOM,__blob)"
if [ ! -f "$SRC/random.bin" ]; then head -c 65536 /dev/urandom > "$SRC/random.bin"; fi
python3 - "$SRC/random.bin" "$BUILD/random_blob.c" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write('/* generated by build.sh from gen/src/random.bin -- do not edit */\n#include <stdio.h>\n')
    f.write('__attribute__((section("__RANDOM,__blob"))) const unsigned char random_blob[%d] = {\n' % len(data))
    for i in range(0, len(data), 32):
        f.write(','.join(str(b) for b in data[i:i+32]) + ',\n')
    f.write('};\nint main(void){ unsigned s=0; for(int i=0;i<%d;i++) s+=random_blob[i]; printf("sum=%%u\\n", s); return 0; }\n' % len(data))
PY
"$CC" -arch arm64 "${CFLAGS[@]}" -o high-entropy "$BUILD/random_blob.c"
log "fake-packed (__XHDR segment)"
"$CC" -arch arm64 "${CFLAGS[@]}" -o fake-packed "$SRC/xhdr.c"

# ---------------------------------------------------------------- f. zig
log "hello-zig (zig build-exe -O ReleaseSmall)"
( cd "$BUILD" && "$ZIG" build-exe "$SRC/hello.zig" -O ReleaseSmall -femit-bin="$CORPUS/hello-zig" )
rm -f "$CORPUS/hello-zig.o"

# ---------------------------------------------------------------- g. legacy bind opcodes
log "legacy-bind (-Wl,-no_fixup_chains)"
"$CC" -arch arm64 "${CFLAGS[@]}" -Wl,-no_fixup_chains -o legacy-bind "$SRC/legacy.c"
if /usr/bin/otool -l legacy-bind | /usr/bin/grep -q LC_DYLD_CHAINED_FIXUPS; then echo "legacy-bind unexpectedly has chained fixups" >&2; exit 1; fi
/usr/bin/otool -l legacy-bind | /usr/bin/grep -q LC_DYLD_INFO_ONLY || { echo "legacy-bind lacks LC_DYLD_INFO_ONLY" >&2; exit 1; }

# ---------------------------------------------------------------- h. app bundle
log "Hello.app"
rm -rf Hello.app
# No Contents/Resources: git cannot store an empty directory, so a clone would lack it and the
# bundle walk (tests/golden/Hello.app.bundle.files.txt) would count a different number of entries.
mkdir -p Hello.app/Contents/MacOS Hello.app/Contents/Frameworks
cp -f hello-objc Hello.app/Contents/MacOS/Hello
cp -f libhello.dylib Hello.app/Contents/Frameworks/libhello.dylib
cp -f "$SRC/Info.plist" Hello.app/Contents/Info.plist
"$PLUTIL" -convert binary1 Hello.app/Contents/Info.plist
cp -f "$SRC/Info.plist" Hello-Info.plist.xml               # XML twin of the binary plist
# sign inner-to-outer (Apple's recommended order; --deep is deprecated)
"$CODESIGN" -s - -f Hello.app/Contents/Frameworks/libhello.dylib
"$CODESIGN" -s - -f Hello.app
"$CODESIGN" --verify --strict -v Hello.app

# ---------------------------------------------------------------- i. quarantine xattr
# Format: <flags hex>;<unix time hex>;<agent name>;<UUID>   (flags 0x0083 = downloaded by a
# user-agent app, LSQuarantineTypeWebDownload, not yet approved by Gatekeeper)
log "hello-quarantined"
cp -f hello-c hello-quarantined
"$XATTR" -w com.apple.quarantine "0083;68c3a1b2;Safari;9B2E1C3A-5F4D-4E6B-8A7C-1D2E3F4A5B6C" hello-quarantined

# ---------------------------------------------------------------- j. malformed / patched
log "malformed fixtures"
python3 "$HERE/malform.py" "$CORPUS"

# ---------------------------------------------------------------- size guard
for f in hello-c hello-x86_64 hello-fat hello-objc libhello.dylib hello-usedylib hello-adhoc hello-entitled \
         hello-unsigned high-entropy fake-packed hello-zig legacy-bind hello-quarantined; do
    sz=$(stat -f %z "$f")
    [ "$sz" -lt 204800 ] || echo "WARNING: $f is $sz bytes (> 200 KB)" >&2
done
log "done"
ls -l "$CORPUS"
